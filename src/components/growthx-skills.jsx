function GrowthXSkills() {
  const [isVisible, setIsVisible] = useState(false)
  const sectionRef = useRef(null)

  useEffect(() => {
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setIsVisible(true)
          observer.unobserve(entry.target)
        }
      },
      {
        threshold: 0.15,
        rootMargin: '0px 0px -50px 0px',
      }
    )

    if (sectionRef.current) {
      observer.observe(sectionRef.current)
    }

    return () => observer.disconnect()
  }, [])

  return (
    <section
      className={`growthx-skills ${isVisible ? 'is-visible' : ''}`}
      ref={sectionRef}
    >
      <div className="growthx-skills__container footer-container">
        <span className="growthx-skills__eyebrow">What you'll achieve</span>
        <h2 className="growthx-skills__title">Skills you'll walk away with.</h2>

        <div className="growthx-skills__grid">
          {skillsData.map((skill, index) => (
            <div
              className="growthx-skills__card"
              key={index}
              style={{ '--card-index': index }}
            >
              <div className="growthx-skills__card-icon">{skill.icon}</div>
              <p className="growthx-skills__card-text">{skill.text}</p>
            </div>
          ))}
        </div>
      </div>
    </section>
  )
}

